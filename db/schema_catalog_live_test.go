// assertLiveCatalogRoundTrip 在新连接安装导出结果，逐次验证实时、内存和重载后的字段属性。
func assertLiveCatalogRoundTrip(t *testing.T, database, fresh *db.DB, table string, verify func([]db.SchemaColumn)) {
	t.Helper()
	check := func(source *db.DB, refresh bool) {
		t.Helper()
		info, err := source.GetSchemaInfo(t.Context(), table, refresh)
		if err != nil {
			t.Fatal(err)
		}
		verify(info.Columns)
	}
	check(database, true)
	check(database, false)
	const identity = "live-column-catalog"
	content, err := database.ExportSchemaCache(t.Context(), identity, []string{table})
	if err != nil {
		t.Fatal(err)
	}
	if err := fresh.LoadSchemaCache(content, identity); err != nil {
		t.Fatal(err)
	}
	check(fresh, false)
}

func testPostgresCatalogSearchPath(t *testing.T) {
	admin := connectLiveSQL(t, "pgsql")
	first, second := liveSQLTableName(), liveSQLTableName()
	for _, namespace := range []string{first, second} {
		if _, err := admin.Execute("CREATE SCHEMA " + namespace); err != nil {
			t.Fatal(err)
		}
		t.Cleanup(func() {
			if _, err := admin.Execute("DROP SCHEMA " + namespace + " CASCADE"); err != nil {
				t.Error(err)
			}
		})
	}
	// 让连接池的每一条物理连接使用相同搜索路径，包括重新打开的连接。
	config, _ := liveSQLConfigFromEnv("pgsql")
	config.Params["search_path"] = first + "," + second
	open := func() *db.DB {
		t.Helper()
		connection, err := (&connector.Pgsql{}).Connect(config)
		if err != nil {
			t.Fatal(err)
		}
		database := db.NewDB(connection)
		t.Cleanup(func() { _ = database.Close() })
		return database
	}
	database, fresh := open(), open()
	const name = "OrderLines"
	check := func(table, field string) {
		t.Helper()
		assertLiveCatalogRoundTrip(t, database, fresh, table, func(columns []db.SchemaColumn) {
			t.Helper()
			if len(columns) != 1 || columns[0].Name != field {
				t.Fatalf("%s 应解析到含 %s 的关系，实际字段为 %+v", table, field, columns)
			}
		})
	}
	if _, err := admin.Execute("CREATE TABLE " + second + `."OrderLines" (later integer)`); err != nil {
		t.Fatal(err)
	}
	check(name, "later")
	if _, err := admin.Execute("CREATE TABLE " + first + `."OrderLines" (earlier integer)`); err != nil {
		t.Fatal(err)
	}
	check(name, "earlier")
	check(second+"."+name, "later")
	if _, err := database.GetSchemaInfo(t.Context(), "orderlines", true); err == nil {
		t.Fatal("不存在的小写表名不应命中混合大小写的表")
	}
}

func testPostgresCatalogPrimaryKeys(t *testing.T) {
	database, fresh := connectLiveSQL(t, "pgsql"), connectLiveSQL(t, "pgsql")
	for _, tc := range []struct {
		name, constraint     string
		idPrimary, tenantKey bool
	}{
		{"单列包含", ", PRIMARY KEY(id) INCLUDE (note)", true, false},
		{"复合包含", ", PRIMARY KEY(tenant, id) INCLUDE (note)", true, true},
		{"普通主键", ", PRIMARY KEY(id)", true, false},
		{"唯一约束", ", UNIQUE(id) INCLUDE (note)", false, false},
		{"无主键", "", false, false},
	} {
		t.Run(tc.name, func(t *testing.T) {
			table := liveSQLTableName()
			if _, err := database.Execute("CREATE TABLE " + table + " (id integer GENERATED BY DEFAULT AS IDENTITY, tenant integer, note text" + tc.constraint + ")"); err != nil {
				t.Fatal(err)
			}
			t.Cleanup(func() {
				if _, err := database.Execute("DROP TABLE " + table); err != nil {
					t.Error(err)
				}
			})
			assertLiveCatalogRoundTrip(t, database, fresh, table, func(columns []db.SchemaColumn) {
				t.Helper()
				if len(columns) != 3 {
					t.Fatalf("字段个数错误：%+v", columns)
				}
				id, tenant, note := columns[0], columns[1], columns[2]
				if id.Name != "id" || id.PrimaryKey != tc.idPrimary || id.Nullable || !id.AutoIncrement ||
					tenant.Name != "tenant" || tenant.PrimaryKey != tc.tenantKey || tenant.Nullable == tc.tenantKey || tenant.AutoIncrement ||
					note.Name != "note" || note.PrimaryKey || !note.Nullable || note.AutoIncrement {
					t.Fatalf("主键、可空或自增属性错误：%+v", columns)
				}
			})
		})
	}
}
